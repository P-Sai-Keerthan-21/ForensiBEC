"""Evaluation metrics and the research evaluation runner.

Separation of results
---------------------
Two result families exist in this project and must never be merged:

  DEVELOPMENT RESULTS  - the forensic rule engine on data/samples (26 hand-
                         written messages). Reported by tests/test_validation.py.
  RESEARCH RESULTS     - ML baselines on data/research (900 generated messages).
                         Reported here.

Both are synthetic. Neither is a real-world accuracy estimate. Every artifact
this module writes carries that statement in its own payload, so a number
cannot be separated from its caveat by being copied out of context.
"""

from __future__ import annotations

import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)

from .baselines import (
    MODELS,
    RANDOM_SEED,
    FeatureSpace,
    ModelSpec,
    labels_of,
    predict,
    train,
)
from .features import FEATURE_GROUPS, ExtractedSample, feature_schema, load_split

RESEARCH_DATA = Path("data") / "research"
RESULTS_DIR = Path("output") / "research"

PROVENANCE = (
    "SYNTHETIC research corpus (data/research, generated by "
    "data/build_research_corpus.py). Template-generated data has learnable "
    "generative structure, so these figures are an OPTIMISTIC UPPER BOUND and "
    "are NOT an estimate of real-world accuracy."
)


def compute_metrics(y_true: np.ndarray, y_pred: np.ndarray,
                    scores: np.ndarray | None = None) -> dict[str, Any]:
    """Full metric set for a binary classification result."""
    matrix = confusion_matrix(y_true, y_pred, labels=[0, 1])
    tn, fp, fn, tp = (int(v) for v in matrix.ravel())

    metrics: dict[str, Any] = {
        "accuracy": round(float(accuracy_score(y_true, y_pred)), 4),
        "precision": round(float(precision_score(y_true, y_pred, zero_division=0)), 4),
        "recall": round(float(recall_score(y_true, y_pred, zero_division=0)), 4),
        "f1": round(float(f1_score(y_true, y_pred, zero_division=0)), 4),
        "confusion_matrix": {
            "true_negative": tn, "false_positive": fp,
            "false_negative": fn, "true_positive": tp,
        },
        "false_positive_rate": round(fp / (fp + tn), 4) if (fp + tn) else 0.0,
        "false_negative_rate": round(fn / (fn + tp), 4) if (fn + tp) else 0.0,
        "support": {"benign": int(tn + fp), "malicious": int(fn + tp)},
    }

    # AUC is undefined when only one class is present; say so rather than
    # emitting a misleading 0.0.
    if scores is not None and len(set(y_true.tolist())) > 1:
        metrics["roc_auc"] = round(float(roc_auc_score(y_true, scores)), 4)
        metrics["pr_auc"] = round(float(average_precision_score(y_true, scores)), 4)
    else:
        metrics["roc_auc"] = None
        metrics["pr_auc"] = None

    return metrics


def environment() -> dict[str, Any]:
    """Reproducibility record written alongside every result file."""
    import sklearn

    return {
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "numpy": np.__version__,
        "scikit_learn": sklearn.__version__,
        "random_seed": RANDOM_SEED,
    }


def load_corpus() -> dict[str, list[ExtractedSample]]:
    """Load and featurise all three splits."""
    splits: dict[str, list[ExtractedSample]] = {}
    for name in ("train", "validation", "test"):
        splits[name] = load_split(RESEARCH_DATA / name)
    return splits


def class_distribution(samples: list[ExtractedSample]) -> dict[str, int]:
    out: dict[str, int] = {}
    for sample in samples:
        out[sample.label_name] = out.get(sample.label_name, 0) + 1
    return out


def evaluate_model(spec: ModelSpec, splits: dict[str, list[ExtractedSample]],
                   groups: list[str], use_text: bool) -> dict[str, Any]:
    """Train on train, report on validation and test."""
    space = FeatureSpace(groups, use_text)
    x_train = space.fit_transform(splits["train"])
    y_train = labels_of(splits["train"])

    model = train(spec, x_train, y_train)

    result: dict[str, Any] = {
        "model": spec.key,
        "model_label": spec.label,
        "n_features": space.n_features,
        "splits": {},
    }

    for split_name in ("validation", "test"):
        samples = splits[split_name]
        x = space.transform(samples)
        y = labels_of(samples)
        y_pred, scores = predict(model, x)
        result["splits"][split_name] = compute_metrics(y, y_pred, scores)

    return result


def run_evaluation(output_dir: Path = RESULTS_DIR) -> dict[str, Any]:
    """Train and evaluate every baseline on the full feature space."""
    splits = load_corpus()
    groups = [g for g in FEATURE_GROUPS if g != "text"]

    corpus_meta_file = RESEARCH_DATA / "metadata" / "corpus.json"
    corpus_meta = (
        json.loads(corpus_meta_file.read_text(encoding="utf-8"))
        if corpus_meta_file.exists() else {}
    )

    results: dict[str, Any] = {
        "result_type": "RESEARCH TEST RESULTS",
        "provenance": PROVENANCE,
        "not_real_world_accuracy": True,
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": environment(),
        "corpus": {
            "source": str(RESEARCH_DATA),
            "seed": corpus_meta.get("seed"),
            "corpus_sha256": corpus_meta.get("corpus_sha256"),
            "sizes": {k: len(v) for k, v in splits.items()},
            "class_distribution": {k: class_distribution(v) for k, v in splits.items()},
        },
        "feature_schema": feature_schema(splits["train"]),
        "models": [],
    }

    for spec in MODELS:
        result = evaluate_model(spec, splits, groups, use_text=True)
        result["config"] = spec.config()
        results["models"].append(result)

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "evaluation.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    return results


def format_table(results: dict[str, Any], split: str = "test") -> str:
    """Human-readable comparison table."""
    header = (
        f"{'Model':<24}{'Prec':>8}{'Rec':>8}{'F1':>8}"
        f"{'Acc':>8}{'ROC':>8}{'PR':>8}{'FPR':>8}{'FNR':>8}"
    )
    lines = [header, "-" * len(header)]
    for entry in results["models"]:
        m = entry["splits"][split]
        lines.append(
            f"{entry['model_label']:<24}"
            f"{m['precision']:>8.3f}{m['recall']:>8.3f}{m['f1']:>8.3f}"
            f"{m['accuracy']:>8.3f}"
            f"{(m['roc_auc'] if m['roc_auc'] is not None else float('nan')):>8.3f}"
            f"{(m['pr_auc'] if m['pr_auc'] is not None else float('nan')):>8.3f}"
            f"{m['false_positive_rate']:>8.3f}{m['false_negative_rate']:>8.3f}"
        )
    return "\n".join(lines)


def main() -> int:
    print("Running RESEARCH evaluation on the synthetic research corpus.")
    print(f"  {PROVENANCE}\n")

    results = run_evaluation()

    print(f"corpus: {results['corpus']['sizes']}")
    print(f"features: {results['feature_schema']['total_structured_features']} structured "
          f"+ TF-IDF text\n")
    print("TEST SPLIT")
    print(format_table(results, "test"))
    print()
    print("VALIDATION SPLIT")
    print(format_table(results, "validation"))
    print(f"\nwritten: {RESULTS_DIR / 'evaluation.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
